"""
bilibili.py — Search and resolve Bilibili videos using official Wbi signing.
Zero heavy dependencies, pure requests + standard libraries.
"""

import hashlib
import os
import re
import time
import urllib.parse
import requests

HEADERS = {
    "User-Agent": (
        "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
        "AppleWebKit/537.36 (KHTML, like Gecko) "
        "Chrome/120.0.0.0 Safari/537.36"
    ),
    "Referer": "https://www.bilibili.com/",
}

MIXIN_KEY_ENC_TAB = [
    46, 47, 18, 2, 53, 8, 23, 32, 15, 50, 10, 31, 58, 3, 45, 35, 27, 43, 5, 49,
    33, 9, 42, 19, 29, 28, 14, 39, 12, 38, 41, 13, 37, 48, 7, 16, 24, 55, 40,
    61, 26, 17, 0, 1, 60, 51, 30, 4, 22, 25, 54, 21, 56, 59, 6, 63, 57, 62, 11,
    36, 20, 34, 44, 52
]


def _get_mixin_key(orig: str) -> str:
    """Generate mixin key for Wbi signing."""
    return "".join([orig[i] for i in MIXIN_KEY_ENC_TAB])[:32]


def _enc_wbi(params: dict, img_key: str, sub_key: str) -> dict:
    """Sign params with Wbi algorithm."""
    mixin_key = _get_mixin_key(img_key + sub_key)
    curr_time = round(time.time())
    params["wts"] = curr_time
    params = dict(sorted(params.items()))
    # Filter disallowed characters
    params = {
        k: "".join(filter(lambda chr: chr not in "!'()*", str(v)))
        for k, v in params.items()
    }
    query = urllib.parse.urlencode(params)
    wbi_sign = hashlib.md5((query + mixin_key).encode()).hexdigest()
    params["w_rid"] = wbi_sign
    return params


def search_bilibili(keyword: str, limit: int = 5) -> list[dict]:
    """
    Search Bilibili for video candidates.
    Returns list of dicts with: id, title, uploader, duration_str, url, thumbnail, platform ('bilibili')
    """
    session = requests.Session()
    # 1. Fetch nav to get Wbi keys
    try:
        nav_resp = session.get("https://api.bilibili.com/x/web-interface/nav", headers=HEADERS, timeout=8).json()
        wbi_img = nav_resp.get("data", {}).get("wbi_img", {})
        img_key = wbi_img.get("img_url", "").rsplit("/", 1)[1].split(".")[0]
        sub_key = wbi_img.get("sub_url", "").rsplit("/", 1)[1].split(".")[0]
        if not img_key or not sub_key:
            return []
    except Exception as e:
        print(f"[Bilibili] Failed to fetch nav keys: {e}")
        return []

    # 2. Get buvid cookies
    try:
        session.get("https://api.bilibili.com/x/frontend/finger/spi", headers=HEADERS, timeout=5)
    except Exception:
        pass

    # 3. Sign parameters and search
    params = {
        "keyword": keyword,
        "search_type": "video",
        "page_size": limit,
    }
    signed = _enc_wbi(params, img_key, sub_key)
    search_url = "https://api.bilibili.com/x/web-interface/wbi/search/type"

    candidates = []
    try:
        resp = session.get(search_url, params=signed, headers=HEADERS, timeout=10)
        data = resp.json()
        if data.get("code") != 0:
            print(f"[Bilibili] Search code {data.get('code')}: {data.get('message')}")
            return []

        results = data.get("data", {}).get("result", [])
        for item in results[:limit]:
            bvid = item.get("bvid") or ""
            # Strip XML/HTML highlight tags from title like <em class="keyword">...</em>
            raw_title = item.get("title", "")
            clean_title = re.sub(r"<[^>]+>", "", raw_title)

            author = item.get("author", "B站UP主")
            pic = item.get("pic", "")
            if pic and pic.startswith("//"):
                pic = "https:" + pic

            dur_str = item.get("duration", "0:00")
            url = f"https://www.bilibili.com/video/{bvid}"

            candidates.append({
                "id": bvid,
                "title": clean_title,
                "uploader": author,
                "duration_str": dur_str,
                "url": url,
                "thumbnail": pic,
                "platform": "bilibili"
            })
    except Exception as e:
        print(f"[Bilibili] Search failed: {e}")

    return candidates


# ============================================================
# Official Bilibili Web QR Code Login -> Netscape cookies.txt
# ============================================================

# Keep active QR login sessions keyed by qrcode_key so cookies persist across poll
_QR_SESSIONS: dict[str, tuple[float, requests.Session]] = {}


def _cleanup_expired_qr_sessions() -> None:
    """Drop stale in-memory QR login sessions older than 5 minutes."""
    now = time.time()
    expired = [k for k, (ts, _) in _QR_SESSIONS.items() if now - ts > 300]
    for k in expired:
        _QR_SESSIONS.pop(k, None)


def save_netscape_cookies(cookie_jar, out_path: str) -> None:
    """Write a requests CookieJar to a standard Netscape cookies.txt file for yt-dlp."""
    default_exp = int(time.time() + 180 * 86400)
    lines = [
        "# Netscape HTTP Cookie File",
        "# Generated by Music Rec Video Studio (Bilibili QR Login)",
        "",
    ]
    seen: set[tuple[str, str, str]] = set()
    for c in cookie_jar:
        domain = c.domain or ".bilibili.com"
        if domain == "bilibili.com":
            domain = ".bilibili.com"
        include_sub = "TRUE" if domain.startswith(".") else "FALSE"
        path = c.path or "/"
        secure = "TRUE" if c.secure else "FALSE"
        expires = int(c.expires) if c.expires else default_exp
        key = (domain, path, c.name)
        if key in seen:
            continue
        seen.add(key)
        lines.append(f"{domain}\t{include_sub}\t{path}\t{secure}\t{expires}\t{c.name}\t{c.value}")

    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def load_netscape_cookies(cookie_path: str) -> dict[str, str]:
    """Read key=value cookie pairs from a Netscape cookies.txt file."""
    cookies: dict[str, str] = {}
    if not cookie_path or not os.path.isfile(cookie_path):
        return cookies
    with open(cookie_path, "r", encoding="utf-8", errors="ignore") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split("\t")
            if len(parts) >= 7:
                cookies[parts[5]] = parts[6]
    return cookies


def generate_bilibili_qr() -> dict:
    """Request a new Bilibili web login QR code URL and qrcode_key."""
    _cleanup_expired_qr_sessions()
    session = requests.Session()
    # Initialize buvid cookies before login
    try:
        session.get("https://api.bilibili.com/x/frontend/finger/spi", headers=HEADERS, timeout=5)
    except Exception:
        pass

    resp = session.get(
        "https://passport.bilibili.com/x/passport-login/web/qrcode/generate",
        headers=HEADERS,
        timeout=10,
    ).json()
    if resp.get("code") != 0:
        raise RuntimeError(resp.get("message") or "获取 B 站登录二维码失败")

    data = resp.get("data") or {}
    qr_url = data.get("url") or ""
    qr_key = data.get("qrcode_key") or ""
    if not qr_url or not qr_key:
        raise RuntimeError("B 站二维码响应缺少 url 或 qrcode_key")

    _QR_SESSIONS[qr_key] = (time.time(), session)
    return {"qrcode_key": qr_key, "url": qr_url}


def poll_bilibili_qr(qrcode_key: str, cookies_path: str) -> dict:
    """
    Poll Bilibili QR login status.
    When confirmed (code == 0), saves full cookies to cookies_path in Netscape format.
    """
    entry = _QR_SESSIONS.get(qrcode_key)
    session = entry[1] if entry else requests.Session()

    resp = session.get(
        "https://passport.bilibili.com/x/passport-login/web/qrcode/poll",
        params={"qrcode_key": qrcode_key},
        headers=HEADERS,
        timeout=10,
    ).json()

    data = resp.get("data") or {}
    code = data.get("code")

    if code == 86101:
        return {"status": "waiting", "message": "请使用手机 B 站 App 扫码登录"}
    if code == 86090:
        return {"status": "scanned", "message": "已扫码，请在手机上点击「确认登录」"}
    if code == 86038:
        _QR_SESSIONS.pop(qrcode_key, None)
        return {"status": "expired", "message": "二维码已过期，请点击刷新"}
    if code == 0:
        # Fetch nav once with the logged-in session to ensure all web cookies are populated
        try:
            session.get("https://api.bilibili.com/x/web-interface/nav", headers=HEADERS, timeout=8)
        except Exception:
            pass
        save_netscape_cookies(session.cookies, cookies_path)
        _QR_SESSIONS.pop(qrcode_key, None)
        user_info = get_bilibili_login_status(cookies_path)
        return {
            "status": "success",
            "message": "B 站登录成功！Cookie 已自动保存",
            "user": user_info,
        }

    return {"status": "error", "message": data.get("message") or f"未知状态码: {code}"}


def get_bilibili_login_status(cookies_path: str) -> dict:
    """Check whether cookies.txt contains a valid Bilibili login session and VIP status."""
    cookies = load_netscape_cookies(cookies_path)
    if not cookies.get("SESSDATA"):
        return {"logged_in": False, "uname": "", "is_vip": False, "vip_label": ""}

    try:
        resp = requests.get(
            "https://api.bilibili.com/x/web-interface/nav",
            headers=HEADERS,
            cookies=cookies,
            timeout=8,
        ).json()
        data = resp.get("data") or {}
        if data.get("isLogin"):
            vip_status = int(data.get("vipStatus") or 0)
            vip_label = (data.get("vip_label") or {}).get("text") or ""
            return {
                "logged_in": True,
                "uname": data.get("uname") or "B站用户",
                "is_vip": vip_status == 1,
                "vip_label": vip_label,
            }
    except Exception:
        pass

    return {"logged_in": False, "uname": "", "is_vip": False, "vip_label": ""}


def clear_bilibili_cookies(cookies_path: str) -> None:
    """Delete saved local Bilibili cookies.txt file."""
    if cookies_path and os.path.isfile(cookies_path):
        os.remove(cookies_path)


